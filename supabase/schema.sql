-- Esquema inicial para Supabase. Revise e aplique políticas RLS antes de produção.
create type account_role as enum ('customer', 'professional', 'admin');

create table profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role account_role not null default 'customer',
  full_name text not null,
  phone text,
  email text,
  city text,
  state text,
  created_at timestamptz not null default now()
);

create table professional_profiles (
  user_id uuid primary key references profiles(id) on delete cascade,
  bio text,
  service_radius_km integer default 20,
  service_areas text[] default '{}',
  verified boolean not null default false
);

create table specialties (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table professional_specialties (
  professional_id uuid references profiles(id) on delete cascade,
  specialty_id bigint references specialties(id) on delete cascade,
  primary key (professional_id, specialty_id)
);

create table service_requests (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references profiles(id),
  specialty_id bigint references specialties(id),
  description text not null,
  address_area text,
  urgency text,
  status text not null default 'open',
  created_at timestamptz not null default now()
);

create table quotes (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references service_requests(id) on delete cascade,
  professional_id uuid not null references profiles(id),
  amount numeric(12,2) not null check (amount >= 0),
  message text,
  status text not null default 'sent',
  created_at timestamptz not null default now()
);

create table reviews (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references service_requests(id),
  customer_id uuid not null references profiles(id),
  professional_id uuid not null references profiles(id),
  rating integer not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now()
);

insert into specialties(name) values
('Elétrica'),('Hidráulica'),('Pintura'),('Marmoraria'),('Marcenaria'),
('Montagem de móveis'),('Pedreiro'),('Limpeza'),('Jardinagem'),('Ar-condicionado')
on conflict do nothing;

